#!/usr/bin/env python3
"""Generate the flash-resident FLOW v3 OKLCH color lookup table."""

import argparse
import math
from pathlib import Path


HUE_STEPS = 72
LIGHTNESS_STEPS = 64
BASS_HUE_DEGREES = 195.0


def linear_to_srgb(value):
    if value <= 0.0031308:
        return 12.92 * value
    return 1.055 * value ** (1.0 / 2.4) - 0.055


def srgb_to_linear(value):
    if value <= 0.04045:
        return value / 12.92
    return ((value + 0.055) / 1.055) ** 2.4


def oklch_to_linear_srgb(lightness, chroma, hue_degrees):
    hue = math.radians(hue_degrees)
    a = chroma * math.cos(hue)
    b = chroma * math.sin(hue)
    l_value = (lightness + 0.3963377774 * a + 0.2158037573 * b) ** 3
    m_value = (lightness - 0.1055613458 * a - 0.0638541728 * b) ** 3
    s_value = (lightness - 0.0894841775 * a - 1.2914855480 * b) ** 3
    return (
        4.0767416621 * l_value - 3.3077115913 * m_value
        + 0.2309699292 * s_value,
        -1.2684380046 * l_value + 2.6097574011 * m_value
        - 0.3413193965 * s_value,
        -0.0041960863 * l_value - 0.7034186147 * m_value
        + 1.7076147010 * s_value,
    )


def vivid_color(hue, lightness):
    if lightness <= 0.001:
        return (0, 0, 0)
    low = 0.0
    high = 0.4
    for _ in range(14):
        candidate = (low + high) * 0.5
        linear = oklch_to_linear_srgb(lightness, candidate, hue)
        if min(linear) >= 0.0 and max(linear) <= 1.0:
            low = candidate
        else:
            high = candidate
    linear = oklch_to_linear_srgb(lightness, low * 0.99, hue)
    return tuple(
        min(255, max(0, round(linear_to_srgb(channel) * 255.0)))
        for channel in linear
    )


def hsv_to_rgb(hue, saturation, value):
    region = hue // 43
    remainder = (hue - region * 43) * 6
    p_value = (value * (255 - saturation)) >> 8
    q_value = (value * (255 - ((saturation * remainder) >> 8))) >> 8
    t_value = (
        value * (255 - ((saturation * (255 - remainder)) >> 8))
    ) >> 8
    colors = (
        (value, t_value, p_value),
        (q_value, value, p_value),
        (p_value, value, t_value),
        (p_value, q_value, value),
        (t_value, p_value, value),
        (value, p_value, q_value),
    )
    return colors[min(region, 5)]


def color_lightness(color):
    red, green, blue = (srgb_to_linear(channel / 255.0) for channel in color)
    l_value = (
        0.4122214708 * red + 0.5363325363 * green + 0.0514459929 * blue
    ) ** (1.0 / 3.0)
    m_value = (
        0.2119034982 * red + 0.6806995451 * green + 0.1073969566 * blue
    ) ** (1.0 / 3.0)
    s_value = (
        0.0883024619 * red + 0.2817188376 * green + 0.6299787005 * blue
    ) ** (1.0 / 3.0)
    return 0.2104542553 * l_value + 0.7936177850 * m_value - 0.0040720468 * s_value


def render():
    lines = [
        "// Generated by tools/generate_flow_v3_color_lut.py; do not edit.",
        "static constexpr int kFlowV3HueSteps = 72;",
        "static constexpr int kFlowV3LightnessSteps = 64;",
        "static constexpr uint8_t kFlowV3VividLut[65][72][3] = {",
    ]
    for light_index in range(LIGHTNESS_STEPS + 1):
        lightness = light_index / LIGHTNESS_STEPS
        colors = [
            vivid_color(hue_index * 360.0 / HUE_STEPS, lightness)
            for hue_index in range(HUE_STEPS)
        ]
        joined = ", ".join(
            f"{{{red}, {green}, {blue}}}" for red, green, blue in colors
        )
        lines.append(f"    {{{joined}}},")
    lines.append("};")
    lines.append("static constexpr float kFlowV3BassLightness[256] = {")
    bass_hue = round(BASS_HUE_DEGREES * 255.0 / 360.0)
    values = [
        color_lightness(hsv_to_rgb(bass_hue, 255, value))
        for value in range(256)
    ]
    for offset in range(0, 256, 8):
        lines.append(
            "    "
            + ", ".join(f"{value:.9f}f" for value in values[offset : offset + 8])
            + ","
        )
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.write_text(render())


if __name__ == "__main__":
    main()
